import 'package:flutter_test/flutter_test.dart';

import 'package:neyam_vaani/data/services/knowledge/hybrid_search.dart';

void main() {
  group('tokenize (unicode-script aware, nv-hash-v1 contract)', () {
    test('lowercases ASCII and splits on punctuation', () {
      expect(tokenize('Hello, World!'), <String>['hello', 'world']);
      expect(tokenize('PM-Kisan'), <String>['pm', 'kisan']);
    });

    test('keeps Tamil words whole', () {
      expect(
        tokenize('வணக்கம் வாணி'),
        <String>['வணக்கம்', 'வாணி'],
      );
      expect(
        tokenize('அவசர உதவி எண் 112'),
        <String>['அவசர', 'உதவி', 'எண்', '112'],
      );
    });

    test('danda is sentence punctuation, not part of the word', () {
      expect(tokenize('नमस्ते। वाणी'), <String>['नमस्ते', 'वाणी']);
    });

    test('digits are word characters; currency signs are not', () {
      expect(tokenize('Call 112 now!'), <String>['call', '112', 'now']);
      expect(
        tokenize('Rs 6,000 ₹5 लाख'),
        <String>['rs', '6', '000', '5', 'लाख'],
      );
    });
  });

  group('embeddings (nv-hash-v1)', () {
    test('dimension is 384 — the Python pipeline contract', () {
      expect(kEmbeddingDim, 384);
      expect(embedText('அவசர உதவி').length, 384);
    });

    test('deterministic: same input, same vector; different input differs', () {
      final List<double> a = embedText('அவசர உதவி எண் 112');
      final List<double> b = embedText('அவசர உதவி எண் 112');
      expect(a, equals(b));
      expect(embedText('hello'), isNot(equals(embedText('goodbye'))));
    });

    test(
      'matches the vector generated by knowledge/build_embeddings.py',
      () {
        // Produced by `python knowledge/build_embeddings.py` (nv-hash-v1):
        // the Python pipeline embeds 'emergency 112' to +0.707107 at index
        // 127 and -0.707107 at index 322 (rounded to 6 decimals; all other
        // components zero). If this test fails after changing either side,
        // the cross-language embedding contract is broken — change both
        // files in one commit and bump the algorithm name (see the
        // contract comment in hybrid_search.dart).
        final List<double> dart = embedText('emergency 112');
        expect(dart.length, 384);
        for (int i = 0; i < dart.length; i++) {
          if (i == 127) {
            expect(dart[i], closeTo(0.707107, 1e-5));
          } else if (i == 322) {
            expect(dart[i], closeTo(-0.707107, 1e-5));
          } else {
            expect(dart[i], 0.0);
          }
        }
      },
    );

    test('cosine of a vector with itself is 1; zero vector is safe', () {
      final List<double> v = embedText('emergency 112');
      expect(cosineSimilarity(v, v), closeTo(1.0, 1e-9));
      expect(
        cosineSimilarity(List<double>.filled(384, 0.0), v),
        0.0,
      );
    });
  });

  group('HybridSearch', () {
    final List<KbEntry> entries = <KbEntry>[
      const KbEntry(
        id: 'torch-howto',
        title: 'How to turn on the torch',
        lang: 'en',
        text: 'Say torch on to turn the flashlight on. Say torch off to turn '
            'it off.',
        tags: <String>['howto', 'torch'],
      ),
      const KbEntry(
        id: 'stove-note',
        title: 'Kitchen notes',
        lang: 'en',
        text: 'Keep a torch near the stove in case the power goes.',
        tags: <String>['cooking'],
      ),
      const KbEntry(
        id: 'ayushman-en',
        title: 'Ayushman Bharat',
        lang: 'en',
        text: 'Free hospital treatment up to Rs 5 lakh per year for '
            'eligible families.',
        tags: <String>['government'],
      ),
    ];

    test('ranking puts the exact-tag match first', () {
      final HybridSearch search = HybridSearch(entries);
      final List<SearchHit> hits = search.search('torch', lang: 'en');
      expect(hits, isNotEmpty);
      expect(hits.first.entry.id, 'torch-howto');
      // The exact-tag entry wins on both channels.
      expect(hits.first.lexicalScore, closeTo(1.0, 1e-9));
    });

    test('score is the 0.6 lexical + 0.4 semantic blend', () {
      final HybridSearch search = HybridSearch(entries);
      final List<SearchHit> hits = search.search('torch', lang: 'en');
      for (final SearchHit hit in hits) {
        expect(
          hit.score,
          closeTo(0.6 * hit.lexicalScore + 0.4 * hit.semanticScore, 1e-9),
        );
      }
    });

    test('threshold filters noise: unknown terms return nothing', () {
      final HybridSearch search = HybridSearch(entries);
      expect(search.search('qqqzzzxyzzy', lang: 'en'), isEmpty);
      // A higher threshold filters even real (but weak) matches.
      expect(search.search('torch', lang: 'en', threshold: 0.95), isEmpty);
    });

    test('language filter restricts candidates and affects BM25 stats', () {
      final HybridSearch search = HybridSearch(entries);
      final List<SearchHit> hits = search.search('torch');
      expect(hits, isNotEmpty);
      expect(hits.every((SearchHit h) => h.entry.lang == 'en'), isTrue);
      // No Tamil entries exist in this corpus.
      expect(search.search('torch', lang: 'ta'), isEmpty);
    });

    test('topK bounds the result', () {
      final HybridSearch search = HybridSearch(entries);
      expect(search.search('torch', lang: 'en', topK: 1).length, 1);
    });

    test('entryById looks entries up', () {
      final HybridSearch search = HybridSearch(entries);
      expect(search.entryById('torch-howto')?.lang, 'en');
      expect(search.entryById('nope'), isNull);
    });
  });
}
